#include "app_printer.h"
#include "usart.h"
#include <string.h>

#define PRINTER_UART_CHUNK_SIZE 128U
#define PRINTER_UART_CHUNK_TIMEOUT_MS 2000U

static void AppPrinter_SetLocalBaud(uint32_t baudRate)
{
  HAL_UART_DeInit(&huart5);
  huart5.Init.BaudRate = baudRate;
  HAL_UART_Init(&huart5);
}

void AppPrinter_InitBaud115200(void)
{
  static const char setBaudZpl[] =
    "^XA\r\n"
    "^SC115200,8,N,1,N,N\r\n"
    "^JUS\r\n"
    "^XZ\r\n";

  AppPrinter_SetLocalBaud(9600);
  AppPrinter_SendBytes((const uint8_t *)setBaudZpl, (uint32_t)strlen(setBaudZpl));
  HAL_Delay(800);
  AppPrinter_SetLocalBaud(115200);
  HAL_Delay(200);
}

void AppPrinter_SendBytes(const uint8_t *data, uint32_t size)
{
  uint32_t offset = 0;

  if (data == 0 || size == 0)
  {
    return;
  }

  while (offset < size)
  {
    uint16_t chunk = (uint16_t)(size - offset);

    if (chunk > PRINTER_UART_CHUNK_SIZE)
    {
      chunk = PRINTER_UART_CHUNK_SIZE;
    }

    if (HAL_UART_Transmit(&huart5,
                          (uint8_t *)&data[offset],
                          chunk,
                          PRINTER_UART_CHUNK_TIMEOUT_MS) != HAL_OK)
    {
      return;
    }

    offset += chunk;
  }
}

void AppPrinter_SendZpl(const char *zpl)
{
  if (zpl == 0)
  {
    return;
  }

  AppPrinter_SendBytes((const uint8_t *)zpl, (uint32_t)strlen(zpl));
}

uint16_t AppPrinter_QueryHostStatus(uint8_t *buffer, uint16_t bufferSize, uint32_t timeoutMs)
{
  static const char query[] = "~HS\r\n";
  uint16_t received = 0;
  uint32_t startTick = HAL_GetTick();
  uint8_t data = 0;

  if (buffer == 0 || bufferSize == 0)
  {
    return 0;
  }

  buffer[0] = 0;
  AppPrinter_SendBytes((const uint8_t *)query, (uint32_t)strlen(query));

  while ((HAL_GetTick() - startTick) < timeoutMs && received < (uint16_t)(bufferSize - 1U))
  {
    if (HAL_UART_Receive(&huart5, &data, 1, 50) == HAL_OK)
    {
      buffer[received++] = data;
      buffer[received] = 0;
    }
    else if (received > 0)
    {
      break;
    }
  }

  return received;
}

static uint8_t AppPrinter_CopyStatusLine(const uint8_t *buffer,
                                         uint16_t size,
                                         uint8_t lineIndex,
                                         char *line,
                                         uint16_t lineSize)
{
  uint16_t i;
  uint16_t pos = 0;
  uint8_t currentLine = 0;
  uint8_t gotData = 0;

  if (buffer == 0 || line == 0 || lineSize == 0)
  {
    return 0;
  }

  line[0] = 0;

  for (i = 0; i < size; i++)
  {
    uint8_t ch = buffer[i];

    if (ch == '\r' || ch == '\n')
    {
      if (currentLine == lineIndex && gotData)
      {
        line[pos] = 0;
        return 1;
      }

      if (gotData)
      {
        currentLine++;
        gotData = 0;
        pos = 0;
      }
      continue;
    }

    if (ch == 0x02 || ch == 0x03)
    {
      continue;
    }

    if (currentLine == lineIndex)
    {
      if ((ch >= '0' && ch <= '9') || ch == ',')
      {
        if (pos < (uint16_t)(lineSize - 1U))
        {
          line[pos++] = (char)ch;
          line[pos] = 0;
          gotData = 1;
        }
      }
    }
    else if ((ch >= '0' && ch <= '9') || ch == ',')
    {
      gotData = 1;
    }
  }

  if (currentLine == lineIndex && gotData)
  {
    line[pos] = 0;
    return 1;
  }

  return 0;
}

static uint8_t AppPrinter_GetCsvField(const char *line,
                                      uint8_t fieldIndex,
                                      char *field,
                                      uint8_t fieldSize)
{
  uint8_t currentField = 0;
  uint8_t pos = 0;
  const char *p = line;

  if (line == 0 || field == 0 || fieldSize == 0)
  {
    return 0;
  }

  field[0] = 0;

  while (*p != 0)
  {
    if (*p == ',')
    {
      if (currentField == fieldIndex)
      {
        field[pos] = 0;
        return 1;
      }

      currentField++;
      pos = 0;
      p++;
      continue;
    }

    if (currentField == fieldIndex)
    {
      if (pos < (uint8_t)(fieldSize - 1U))
      {
        field[pos++] = *p;
        field[pos] = 0;
      }
    }

    p++;
  }

  return (currentField == fieldIndex);
}

static uint8_t AppPrinter_FieldEquals(const char *line, uint8_t index, const char *expected)
{
  char field[12];

  if (!AppPrinter_GetCsvField(line, index, field, sizeof(field)))
  {
    return 0;
  }

  return (strcmp(field, expected) == 0);
}

uint8_t AppPrinter_IsHostStatusDone(const uint8_t *buffer, uint16_t size)
{
  char line1[80];
  char line2[80];

  if (!AppPrinter_CopyStatusLine(buffer, size, 0, line1, sizeof(line1)))
  {
    return 0;
  }

  if (!AppPrinter_CopyStatusLine(buffer, size, 1, line2, sizeof(line2)))
  {
    return 0;
  }

  /* ~HS line 1:
     b=media out, c=pause, eee=formats in receive buffer,
     f=buffer full, h=partial format, j=RAM corrupt, k/l=temp out of range. */
  if (!AppPrinter_FieldEquals(line1, 1, "0")) return 0;
  if (!AppPrinter_FieldEquals(line1, 2, "0")) return 0;
  if (!AppPrinter_FieldEquals(line1, 4, "000")) return 0;
  if (!AppPrinter_FieldEquals(line1, 5, "0")) return 0;
  if (!AppPrinter_FieldEquals(line1, 7, "0")) return 0;
  if (!AppPrinter_FieldEquals(line1, 9, "0")) return 0;
  if (!AppPrinter_FieldEquals(line1, 10, "0")) return 0;
  if (!AppPrinter_FieldEquals(line1, 11, "0")) return 0;

  /* ~HS line 2:
     o=head open, p=ribbon out, t=label waiting in peel/applicator modes. */
  if (!AppPrinter_FieldEquals(line2, 2, "0")) return 0;
  if (!AppPrinter_FieldEquals(line2, 3, "0")) return 0;
  if (!AppPrinter_FieldEquals(line2, 7, "0")) return 0;

  return 1;
}

uint8_t AppPrinter_WaitDone(uint32_t timeoutMs, uint32_t intervalMs)
{
  uint8_t status[256];
  uint16_t statusLen;
  uint32_t startTick = HAL_GetTick();
  uint8_t readyCount = 0;

  while ((HAL_GetTick() - startTick) < timeoutMs)
  {
    statusLen = AppPrinter_QueryHostStatus(status, sizeof(status), 800);

    if (statusLen > 0 && AppPrinter_IsHostStatusDone(status, statusLen))
    {
      readyCount++;
      if (readyCount >= 2)
      {
        return 1;
      }
    }
    else
    {
      readyCount = 0;
    }

    HAL_Delay(intervalMs);
  }

  return 0;
}

